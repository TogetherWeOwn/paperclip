import { execute } from "./execute.js";

function buildContext(config: Record<string, unknown> = {}) {
  return {
    runId: "run-1",
    agent: {
      id: "agent-1",
      companyId: "company-1",
      name: "Codex Coder",
      adapterType: "codex_local",
      adapterConfig: {},
    },
    runtime: {
      sessionId: null,
      sessionParams: null,
      sessionDisplayId: null,
      taskKey: null,
    },
    config: {
      outputInactivityTimeoutMs: null,
      env: { OPENAI_API_KEY: "test-key" },
      ...config,
    },
    context: {},
    onLog: vi.fn(async () => {}),
  };
}

describe("codex_local per-run PID limit", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it("forwards config.runPidLimit to the child and carries pidStats", async () => {
    const result = await execute(buildContext({ runPidLimit: 200 }) as never);

    expect(runAdapterExecutionTargetProcess).toHaveBeenCalledTimes(1);
    expect(runAdapterExecutionTargetProcess).toHaveBeenCalledWith(
      expect.any(String),
      null,
      expect.any(String),
      expect.any(Array),
      expect.objectContaining({ pidLimit: 200 }),
    );
    const resultJson = result.resultJson as {
      pidStats?: { limit: number; exceeded: boolean };
    };
    expect(resultJson.pidStats?.limit).toBe(200);
    expect(resultJson.pidStats?.exceeded).toBe(false);
  });
});
